    choice(t, 1, f"Чему равна сумма {a}/{n} + {b}/{n}?", f"{a + b}/{n}",
           [f"{a + b}/{2 * n}", f"{a + b + 1}/{n}", f"{a + b + 2}/{n}"],
           "При одинаковых знаменателях складываются числители, знаменатель не меняется.")
    n = rng.randint(7, 12); a = rng.randint(4, n - 1); b = rng.randint(1, a - 1)
    inp(t, 1, f"Вычислите: {a}/{n} − {b}/{n}. Ответ запишите обыкновенной дробью.", fr(Fraction(a - b, n)),
        f"{a} − {b} = {a - b}, знаменатель остаётся {n}.")
    a, b = rng.randint(1, 12), rng.randint(2, 12)
    boolean(t, 1, f"Верно ли, что дробь {a}/{b} правильная?", a < b,
            "Дробь правильная, если числитель меньше знаменателя.")
    n = rng.randint(12, 20); ks = rng.sample(range(1, n), 4); small = min(ks)
    choice(t, 1, "Какая из дробей наименьшая?", f"{small}/{n}", [f"{k}/{n}" for k in ks if k != small],
           "При одинаковых знаменателях меньше та дробь, у которой меньше числитель.")
    b = rng.choice([2, 3, 4, 5, 6]); a = rng.randint(1, b - 1); c = rng.randint(1, 2 * b - 1)
    s = Fraction(a, b) + Fraction(c, 2 * b)
    wrong = {f"{a + c}/{3 * b}", f"{a + c}/{b}", f"{a + c + 1}/{2 * b}", f"{a + c + 2}/{2 * b}", f"{a + c}/{4 * b}"} - {fr(s)}
    choice(t, 2, f"Чему равна сумма {a}/{b} + {c}/{2 * b}?", fr(s), sorted(wrong)[:3],
           f"Приводим к знаменателю {2 * b}: {2 * a}/{2 * b} + {c}/{2 * b} = {fr(s)}.")
    b = rng.choice([2, 3, 4, 5, 6]); a = rng.randint(1, b - 1); c = rng.randint(1, 2 * b - 1)
    s = Fraction(a, b) + Fraction(c, 2 * b)
    inp(t, 2, f"Вычислите: {a}/{b} + {c}/{2 * b}. Ответ запишите обыкновенной дробью.", fr(s),
        f"Общий знаменатель {2 * b}: {2 * a}/{2 * b} + {c}/{2 * b} = {fr(s)}.")
    ks = rng.sample(range(1, 8), 4)
    ordering(t, 2, "Расположите дроби в порядке возрастания:", [fr(Fraction(k, 8)) for k in sorted(ks)],
             "Приводим к знаменателю 8 и сравниваем числители: " + ", ".join(f"{k}/8" for k in sorted(ks)) + ".")
    b = rng.choice([3, 4, 5, 6]); a = rng.randint(1, b - 1); c = rng.randint(1, 2 * a - 1)
    d_ = Fraction(a, b) - Fraction(c, 2 * b)
