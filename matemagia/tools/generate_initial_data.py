def decimals(t):
    a, b = D(rng.randint(11, 89)) / 10, D(rng.randint(11, 89)) / 10
    inp(t, 1, f"Вычислите: {dec(a)} + {dec(b)}", dec(a + b), f"Запятая под запятой: {dec(a)} + {dec(b)} = {dec(a + b)}.")
    a, b = D(rng.randint(11, 59)) / 10, D(rng.randint(11, 59)) / 10; s = a + b
    choice(t, 1, f"Чему равна сумма {dec(a)} + {dec(b)}?", dec(s), [dec(s + D("0.1")), dec(s - D("0.1")), dec(s + 1)],
           f"Складываем в столбик, запятая под запятой: {dec(s)}.")
    x, y = D(rng.randint(1, 9)) / 10, D(rng.randint(10, 99)) / 100
    boolean(t, 1, f"Верно ли, что {dec(x)} > {dec(y)}?", x > y, f"Сравниваем: {dec(x)} {'>' if x > y else '<'} {dec(y)}.")
    ns = rng.sample(range(10, 99), 4); vals = sorted(D(n) / 100 for n in ns)
    ordering(t, 1, "Расположите числа в порядке возрастания:", [dec(v) for v in vals],
             "Сравниваем десятичные дроби по разрядам слева направо.")
    a, b = D(rng.randint(200, 999)) / 100, D(rng.randint(100, 199)) / 100
    inp(t, 2, f"Вычислите: {dec(a)} − {dec(b)}", dec(a - b), f"Вычитаем в столбик: {dec(a)} − {dec(b)} = {dec(a - b)}.")
    x = D(rng.randint(101, 999)) / 100
    inp(t, 2, f"Вычислите: {dec(x)} × 100", dec(x * 100), "При умножении на 100 запятая сдвигается на два знака вправо.")
    x = D(rng.randint(101, 999)) / 100; r = x.quantize(D("0.1"), rounding=ROUND_HALF_UP)
    ws = [w for w in dict.fromkeys([r + D("0.1"), r - D("0.1"), x.quantize(D("1"), rounding=ROUND_HALF_UP)]) if w != r]
    k = 2
    while len(ws) < 3:
        ws.append(r + D("0.1") * k); k += 1
    choice(t, 2, f"Округлите {dec(x)} до десятых.", dec(r), [dec(w) for w in ws[:3]],
           "Смотрим на цифру сотых: если она 5 или больше, десятые увеличиваем на 1.")
    matching(t, 2, "Сопоставьте десятичные и обыкновенные дроби:",
             [("0,5", "1/2"), ("0,25", "1/4"), ("0,75", "3/4"), ("0,2", "1/5")],
             "0,5 = 5/10 = 1/2; 0,25 = 25/100 = 1/4; 0,75 = 3/4; 0,2 = 2/10 = 1/5.")
    a, b = D(rng.randint(11, 49)) / 10, D(rng.randint(11, 29)) / 10
    inp(t, 3, f"Вычислите: {dec(a)} × {dec(b)}", dec(a * b),
        f"Умножаем как целые ({int(a * 10)} × {int(b * 10)}) и отделяем два знака: {dec(a * b)}.")
    dv = rng.choice([D("0.5"), D("0.2"), D("0.25")]); q = rng.randint(3, 40)
    inp(t, 3, f"Вычислите: {dec(dv * q)} : {dec(dv)}", q, f"{dec(dv)} × {q} = {dec(dv * q)}, значит ответ {q}.")
    x = D(rng.randint(11, 99)) / 10
    choice(t, 3, f"Сколько сантиметров в {dec(x)} м?", dec(x * 100), [dec(x * 10), dec(x * 1000), dec(x)],
           f"1 м = 100 см, поэтому {dec(x)} × 100 = {dec(x * 100)} см.")
    a = D(rng.randint(11, 99)) / 10
    boolean(t, 3, f"Верно ли, что {dec(a)} × 0,1 = {dec(a)} : 10?", True, "Умножить на 0,1 — то же, что разделить на 10.")


