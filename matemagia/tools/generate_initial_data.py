    choice_n(t, 1, f"Найдите x: x + {a} = {x + a}", x, [x + a, a, x + 10], f"x = {x + a} − {a} = {x}.")
    a, b = rng.randint(250, 899), rng.randint(250, 899)
    inp(t, 2, f"Вычислите: {a} + {b}", a + b, f"Складываем столбиком: {a} + {b} = {a + b}.")
    a, b = rng.randint(600, 999), rng.randint(120, 590)
