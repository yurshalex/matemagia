#!/usr/bin/env python
"""Генерация learning/fixtures/initial_data.json: темы, уроки, подготовленные задания, достижения.

Запуск из корня проекта:  python tools/generate_initial_data.py
Ответы вычисляются программой; тексты стоит просмотреть и дополнить через Django Admin.
"""
import json
import random
from decimal import Decimal as D, ROUND_HALF_UP
from fractions import Fraction
from pathlib import Path

rng = random.Random(2026)
TASKS = []


def fr(x):
    x = Fraction(x)
    return str(x.numerator) if x.denominator == 1 else f"{x.numerator}/{x.denominator}"


def dec(x):
    return format(D(x).normalize(), "f").replace(".", ",")


def add(t, kind, d, cond, answer, expl, payload=None):
    TASKS.append({"topic": t, "task_type": kind, "difficulty_level": d, "condition": cond,
                  "content_payload": payload, "correct_answer": answer, "explanation": expl})


def choice(t, d, cond, correct, wrong, expl):
    opts = [correct] + list(wrong)
    assert len(opts) == 4 and len(set(opts)) == 4, (cond, opts)
    rng.shuffle(opts)
    add(t, "choice", d, cond, correct, expl, {"options": opts})


def choice_n(t, d, cond, correct, wrongs, expl):
    ws = []
    for w in wrongs:
        if w != correct and w not in ws and w > 0:
            ws.append(w)
    k = 1
    while len(ws) < 3:
        if correct + k not in ws:
            ws.append(correct + k)
        k += 1
    choice(t, d, cond, str(correct), [str(w) for w in ws[:3]], expl)


def boolean(t, d, cond, value, expl):
    add(t, "boolean", d, cond, "true" if value else "false", expl)


def inp(t, d, cond, answer, expl):
    add(t, "input", d, cond, str(answer), expl)


def ordering(t, d, cond, items, expl):
    shuffled = list(items)
    while shuffled == list(items):
        rng.shuffle(shuffled)
    add(t, "ordering", d, cond, json.dumps(list(items), ensure_ascii=False), expl, {"items": shuffled})


def matching(t, d, cond, pairs, expl):
    right = [r for _, r in pairs]
    rng.shuffle(right)
    add(t, "matching", d, cond, json.dumps(dict(pairs), ensure_ascii=False), expl,
        {"left": [l for l, _ in pairs], "right": right})


