    inp(t, 3, f"Найдите x: 1000 − x = {n}", 1000 - n, f"x = 1000 − {n} = {1000 - n}.")
    a, b, c = (rng.randint(1000, 4000) for _ in range(3))
    inp(t, 3, f"Вычислите: {a} + {b} + {c}", a + b + c, f"{a} + {b} = {a + b}; {a + b} + {c} = {a + b + c}.")
    c = rng.randint(5, 40); b = c + rng.randint(5, 40); a = b + rng.randint(5, 60)
    choice_n(t, 3, f"Чему равно значение выражения {a} − ({b} − {c})?", a - b + c, [a - b - c, a + b - c, a - b + c + 1],
             f"Скобки: {b} − {c} = {b - c}; затем {a} − {b - c} = {a - b + c}.")
    b, c = rng.randint(10, 30), rng.randint(10, 30); a = b + c + rng.randint(5, 50)
    boolean(t, 3, f"Верно ли, что {a} − ({b} + {c}) = {a} − {b} − {c}?", True,
            "Чтобы вычесть сумму, можно вычесть каждое слагаемое по очереди.")


